package com.pixellab.app.ui.assist

/**
 * 离线问答"大脑"：关键词匹配 + 内置知识库，全程不联网。
 *
 * 设计思路（答辩可讲）：
 *   1. 知识库是一个 List<Entry>，每个 Entry 有若干关键词和一条答案；
 *   2. 用户问题做归一化（去空白/转小写）后，逐条检查关键词命中；
 *   3. 命中最多关键词的 Entry 获胜——比"第一个命中就返回"更准，
 *      因为"高斯模糊什么原理"会同时命中"高斯"和"原理"两条，取最长覆盖；
 *   4. 全部未命中时返回引导话术，并列出能回答的话题。
 *
 * 为什么不用大模型？课设要求离线可用、可解释——规则式问答零依赖、
 * 答案可控（能把卷积的信号处理原理讲准确），这正是本项目的强项。
 */
object AssistantBrain {

    /** 一条知识：keywords 任一命中即候选，answer() 返回给用户的完整回答 */
    private data class Entry(val keywords: List<String>, val answer: () -> String)
    private val entries = listOf(
        Entry(listOf("高斯", "gaussian")) {
            """高斯模糊是【可分离卷积】：一个 2D 高斯核可以拆成"水平 1D + 垂直 1D"两次一维卷积。
计算量从 O(N·k²) 降到 O(N·2k)，半径 9 时快约 4.5 倍。
它对图像的作用等价于【低通滤波器】——衰减高频（噪点、细纹理），保留低频（大轮廓），所以看起来"变柔"。
代码在 image/Convolver.kt 的 gaussianBlur()，水平、垂直各跑一遍 convolve1D。"""
        },
        Entry(listOf("锐化", "sharpen", "清晰")) {
            """锐化核是 3×3 卷积：中心权值 5，上下左右 -1，四角 0。
它本质是【恒等 + 拉普拉斯】：输出 = 原图 + (原图 - 模糊分量)，把高频细节放大，
边缘两侧出现过冲，视觉上"更锐"。代码在 FilterPreset.kt 的 SHARPEN。"""
        },
        Entry(listOf("边缘", "edge", "sobel", "轮廓")) {
            """边缘检测用【梯度算子】：像素亮度变化剧烈的地方就是边缘。
· EDGE（Laplacian 四邻域）：各向同性二阶导，对孤立点也敏感；
· SOBEL_V：垂直方向一阶导（[-1,0,1] 与平滑核卷积），对纵向边缘响应最强。
一阶导找极值、二阶导找过零点——这就是信号处理里"卷积求导"的直接应用。"""
        },
        Entry(listOf("浮雕", "emboss")) {
            """浮雕核把权值偏置到左上 (-2,-1,0 / -1,1,1 / 0,1,2)，再用 +128 的偏移量补回灰度。
效果等于【方向性差分】：左上与右下的亮度差被保留，看起来像凸起的雕刻面。"""
        },
        Entry(listOf("灰度", "gray", "黑白")) {
            """灰度化用 BT.601 标准亮度公式：Y = 0.299R + 0.587G + 0.114B。
人眼对绿色最敏感、蓝色最弱，所以不能简单取平均。
实现上为了避开浮点，用整数域 (299r+587g+114b)/1000，单遍 O(N)。"""
        },
        Entry(listOf("卷积", "convolution", "核", "kernel", "原理")) {
            """卷积 = 拿一个 3×3 权值核在图像上滑动，每个位置把邻域像素加权求和。
数学上是二维离散信号与系统的核心运算：空间域卷积 ⇔ 频域乘积。
模糊核低通、锐化核高通、边缘核带通——不同核就是不同滤波器。
本项目的 apply3x3() 用 clamp 处理边界、每通道独立计算并 clamp 到 0~255。"""
        },
        Entry(listOf("怎么用", "使用", "流程", "步骤", "怎么操作")) {
            """三步出图：
1. 图库页点"从相册选图"或"拍照"；
2. 进编辑页，点滤镜芯片（锐化/高斯/边缘/浮雕/灰度……），再点"应用滤镜"；
3. 满意后点"保存到历史"，记录会出现在图库列表和桌面小组件里。
还可以旋转、裁剪（1:1 / 4:3 / 16:9）、文字识别、生成分享卡片。"""
        },
        Entry(listOf("保存", "历史", "记录", "存")) {
            """保存走 Room 数据库：结果图 + 缩略图写入应用专属目录，记录（滤镜、耗时、尺寸、OCR 文本）插入 photos 表。
图库列表和桌面小组件读的都是这张表，保存后小组件会自动刷新。"""
        },
        Entry(listOf("批量", "batch", "队列")) {
            """批量处理选 2~9 张图，选一个滤镜整批套用。
底层用 WorkManager CoroutineWorker：后台队列逐张处理，setProgress 上报"x/y 已完成"，
退出页面甚至杀掉应用都不中断，回来看进度即可。单张失败会跳过，不拖垮整批。"""
        },
        Entry(listOf("识别", "ocr", "文字")) {
            """文字识别用 ML Kit 中文识别模型（bundled 模式，模型打包进 APK，完全离线）。
流程：Bitmap → InputImage → recognizer.process().await() 挂起等结果 → 文本块拼出来。
识别结果会随记录一起存库，图库里可查。"""
        },
        Entry(listOf("分享", "卡片", "share")) {
            """编辑页点右下圆形分享按钮，会生成一张 1080 宽的处理报告卡片：
处理前后对比图 + 滤镜名 + 耗时 + 均值 μ / 标准差 σ + 学号水印，
经 FileProvider 提供临时 URI，调系统分享面板发到微信/QQ 等。"""
        },
        Entry(listOf("小组件", "widget", "桌面")) {
            """P1 桌面小组件显示"最近一次处理"的缩略图和滤镜名。
数据由 runBlocking 查 Room 最新记录得到；保存新记录时调用 notifyDataChanged() 主动刷新。
长按桌面空白处 → 添加小组件 → 像素工坊 即可添加。"""
        },
        Entry(listOf("直方图", "统计", "均值", "标准差", "sigma", "μ")) {
            """统计页展示处理前后的灰度直方图与量化指标：
· 直方图：256 级灰度计数，单遍 O(N) 统计，再按屏宽分桶避免柱子重叠；
· 均值 μ：亮度中心；标准差 σ：对比度（σ 越大反差越强）。
σ 用 E[X²]−E[X]² 在同一遍循环里算完，不占额外内存。"""
        },
        Entry(listOf("权限", "相机", "camera", "授权")) {
            """相机权限是运行时申请的（REQUEST_INSTALL 流程）：拒绝后不闪退，
底部弹 Snackbar"未授权相机，已降级为仅相册选图"，相册功能照常可用——
这是 Android 的【优雅降级】设计。可在系统设置里重新授权。"""
        },
        Entry(listOf("耗时", "性能", "多快", "优化")) {
            """处理性能做了三层优化：
1. Dispatchers.Default 多核并行，不阻塞 UI 线程；
2. 可分离卷积：高斯模糊 O(N·k²) → O(N·2k)；
3. 解码用两次采样法 inSampleSize，大图先降采样到最长边 1280 再进卷积，
   内存和耗时都可控。你看到的"xx ms"徽章就是单次滤镜的真实耗时。"""
        },
        Entry(listOf("裁剪", "crop", "旋转", "rotate")) {
            """几何变换都在 Bitmap 层面完成：
· 旋转 90°：Matrix.postRotate + 新建等尺寸 Bitmap；
· 裁剪：cropToRatio(w, h, ratio) 以中心为基准算最大可裁窗口。
和滤镜共用同一条"应用→预览→保存"管线。"""
        },
        Entry(listOf("你是谁", "助手", "ai", "人工智能", "大模型")) {
            """我是像素工坊内置的离线问答助手：一个关键词匹配 + 知识库引擎，
不联网、不依赖任何大模型服务，所有回答都在本机生成。
你可以问我滤镜原理、操作步骤、保存/批量/识别/分享/小组件/直方图……"""
        }
    )

    /**
     * 归一化 + 命中计分，返回最匹配的答案；无命中返回默认引导。
     */
    fun answer(question: String): String {
        val q = question.trim().lowercase().replace(Regex("\\s+"), "")
        if (q.isEmpty()) return greeting()
        var best: Entry? = null
        var bestScore = 0
        for (e in entries) {
            var score = 0
            for (k in e.keywords) if (k.lowercase() in q) score++
            if (score > bestScore) { best = e; bestScore = score }
        }
        return best?.answer?.invoke() ?: defaultReply()
    }

    fun greeting(): String =
        "你好！我是像素工坊的内置助手 🤖\n滤镜原理、使用步骤、保存分享……任何问题直接问我。"

    private fun defaultReply(): String = """
这个问题我还没学会。我可以回答这些话题：
· 滤镜原理：高斯模糊 / 锐化 / 边缘检测 / 浮雕 / 灰度 / 卷积
· 使用流程、保存与历史、批量处理、文字识别
· 分享卡片、桌面小组件、直方图统计、权限说明、性能优化
换个问法试试，比如"高斯模糊是什么原理？"
""".trimIndent()
}
